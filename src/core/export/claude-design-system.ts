import { BODY_TEXT_CONTRAST, formatRatio } from "../colour/contrast-levels";
import type { ThemeColours, ThemeId } from "../colour/derive-theme";
import type { Diagnostic, FileMap } from "../compile";
import { toJsonFile } from "../json-file";
import type { BundledLogo } from "../logos/bundled-logos";
import { LOGO_GROUP, logoAssetGroup, logoGroupReadme, logoRules } from "../logos/logo-docs";
import type { Project } from "../project";
import type { BundledFont } from "../type/uploaded-fonts";
import { COMPONENTS } from "../components/component-catalogue";
import { claudeComponentFiles } from "./claude-components";
import { claudeTokens, COLOUR_USAGE } from "./claude-tokens";
import type { CardVars } from "./ds-card";

/** The Design System type contract this export is written against (see docs/research/01). */
export const DESIGN_SYSTEM_CONTRACT = "0.2.47";

/** One theme's colours, ready to export. */
export type ExportTheme = { id: ThemeId; name: string; colours: ThemeColours };

/**
 * What the export needs besides the project: when it was made, the checks it should be honest about, uploads,
 * and the compiled CSS variables that static preview cards inline.
 */
export type ExportContext = {
  now: Date;
  diagnostics: Diagnostic[];
  fonts: BundledFont[];
  logos?: BundledLogo[];
  cardVars: CardVars;
};

/**
 * Builds the `project/` files that Claude's Design System artifact type reads, without any file the page generates.
 * The index is the last key, because the type asks for it to be written last.
 */
export function claudeDesignSystemFiles(
  project: Project,
  themes: ExportTheme[],
  { now, diagnostics, fonts, logos = [], cardVars }: ExportContext,
): FileMap {
  const at = now.toISOString();
  // Per the type's instructions, the page fills in sections, blobs and docs.sections itself.
  const index = {
    v: 3,
    layout: "files",
    createdOnFiles: { v: 1, at },
    title: project.meta.name,
    namespace: toIdentifier(project.meta.namespace),
    libraries: [],
    sections: {},
    groups: logos.length ? [LOGO_GROUP] : [],
    assetGroups: logos.length ? { [LOGO_GROUP]: logoAssetGroup(logos) } : {},
    blobs: {},
    docs: { readme: "project/README.md", sections: [] },
    lastChange: {
      by: "Brandkit for Claude",
      at,
      via: "Brandkit for Claude export",
      note: `Generated by Brandkit for Claude for Design System contract ${DESIGN_SYSTEM_CONTRACT}.`,
    },
  };
  return {
    "project/tokens.json": toJsonFile(claudeTokens(project, themes, fonts)),
    "project/README.md": readme(project, themes, diagnostics, logos),
    ...Object.fromEntries(fonts.map(font => [`project/fonts/${font.file}`, font.bytes])),
    ...logoFiles(project, logos),
    // Components end with the Cover, which the type asks to be written last before the index.
    ...claudeComponentFiles(project.meta.name, cardVars),
    "project/design-system.json": toJsonFile(index),
  };
}

function readme(project: Project, themes: ExportTheme[], diagnostics: Diagnostic[], logos: BundledLogo[]): string {
  const themeNames = themes.map(theme => theme.name.toLowerCase()).join(" and ");
  const colourList = COLOUR_USAGE.map(([name, usage]) => `- \`${name}\`: ${usage}`).join("\n");
  const bodyText = formatRatio(BODY_TEXT_CONTRAST);
  // Claude reads the README as fact, so it only promises readable text when every pair delivers it.
  const lowContrast = diagnostics.filter(diagnostic => diagnostic.code === "contrast-low");
  const contrastRule =
    lowContrast.length === 0
      ? `- Every text colour is paired with the surface named in its usage note, and reads at ${bodyText} or better in every theme.`
      : [
          `- Every text colour is paired with the surface named in its usage note. These pairs read below ${bodyText}, so use them only for large or bold text:`,
          ...lowContrast.map(diagnostic => `  - ${diagnostic.message}`),
        ].join("\n");
  return `# ${project.meta.name}

${project.meta.name}'s design system, made with Brandkit for Claude. It has ${themeNames} themes. Use these tokens instead of your own defaults.

## Global rules

- Body text is \`foreground\` on \`background\` or \`card\`. Quieter text is \`muted-foreground\`, never a lighter grey.
${contrastRule}

## Colour

${colourList}

## Type

${typeRules(project)}

## Shape and space

${shapeRules(project)}

## Logo

${logoRules(project, logos)}

## Components

${COMPONENTS.map(component => `- [${component.title}](components/${component.name}/README.md): ${component.summary}`).join("\n")}
`;
}

// Logo files are asset uploads in the Design System; the group README is a plain file beside them.
function logoFiles(project: Project, logos: BundledLogo[]): FileMap {
  if (logos.length === 0) return {};
  const folder = `project/assets/${LOGO_GROUP}`;
  return {
    ...Object.fromEntries(logos.map(logo => [`${folder}/${logo.file}`, logo.bytes])),
    [`${folder}/README.md`]: logoGroupReadme(project, logos),
  };
}

function typeRules(project: Project): string {
  const { display, body, mono } = project.type.families;
  return [
    `- Headings use ${display.family}, running text uses ${body.family} and code uses ${mono.family}.`,
    "- Use the ten text styles in `tokens.json` as they are. Don't invent in-between sizes or weights.",
    "- One `display` line per view at most; most pages start at `h1`.",
  ].join("\n");
}

function shapeRules(project: Project): string {
  const { radii, shadow, borders } = project.shape;
  const rules = [
    "- Space things with the six `space-*` steps only. Use bigger steps between sections than inside them.",
  ];
  if (radii) {
    rules.push(
      `- Corners follow hierarchy: controls \`radius-control\` (${radii.control}px), cards \`radius-card\` (${radii.card}px), dialogs \`radius-dialog\` (${radii.dialog}px), badges \`radius-pill\`. Never one radius on everything.`,
    );
  }
  rules.push(
    shadow.enabled
      ? "- Raised cards use `shadow-raised`; dialogs and menus use `shadow-overlay`. Nothing else gets a shadow."
      : "- Flat: no shadows anywhere, including on hover.",
    borders === "hairline"
      ? "- Separate surfaces with 1px `border` hairlines."
      : "- No borders: separate surfaces with fills (`card` on `background`) and space.",
  );
  return rules.join("\n");
}

// The index namespace is the global a component bundle would assign, so it must be a JS identifier.
function toIdentifier(namespace: string): string {
  const pascal = namespace
    .split("-")
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
  return /^[A-Za-z_$]/.test(pascal) ? pascal : `Brand${pascal}`;
}
